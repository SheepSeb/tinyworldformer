"""Write numbers into Rust source and golden-vector files without losing a bit.

Floats are written as `f32::from_bits(0x...)`, so the Rust side sees exactly the float32 the
Python side computed with; integers are written as decimal literals.
"""

import struct
from pathlib import Path

import numpy as np

RUST_TYPES = {"f32": np.float32, "i8": np.int8, "u8": np.uint8, "u16": np.uint16, "i16": np.int16,
              "u32": np.uint32, "i32": np.int32}


def rust_array(name: str, a: np.ndarray, ty: str) -> str:
    """`pub static NAME: [ty; n] = [...];` with the array flattened in C order."""
    flat = np.asarray(a).reshape(-1)
    if ty == "f32":
        body = ", ".join(f"f32::from_bits(0x{int(x):08x})" for x in flat.astype(np.float32).view(np.uint32))
    else:
        assert ty in RUST_TYPES, f"unknown Rust type {ty}"
        body = ", ".join(str(int(x)) for x in flat.astype(RUST_TYPES[ty]))
    return f"pub static {name}: [{ty}; {len(flat)}] = [{body}];\n"


def rust_const(name: str, value, ty: str = "usize") -> str:
    """`pub const NAME: ty = value;` (strings become `&str`)."""
    if ty == "&str":
        return f'pub const {name}: &str = "{value}";\n'
    if ty == "f32":
        return f"pub const {name}: f32 = f32::from_bits(0x{int(np.float32(value).view(np.uint32)):08x});\n"
    return f"pub const {name}: {ty} = {value};\n"


def write_module(path: Path, parts: list[str], generator: str) -> None:
    """A generated Rust file: a do-not-edit header naming the command that wrote it, then `parts`."""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(f"// @generated by `{generator}`. Do not edit.\n" + "".join(parts))


class Golden:
    """Little-endian golden-vector file: append records, then `save`. The Rust test reads them
    back in the same order (see the `f32s` helper in `tests/golden.rs`)."""

    def __init__(self):
        self.parts: list[bytes] = []

    def u8(self, *values: int) -> "Golden":
        self.parts.append(bytes(values))
        return self

    def u32(self, value: int) -> "Golden":
        self.parts.append(struct.pack("<I", value))
        return self

    def array(self, a: np.ndarray, dtype=np.float32) -> "Golden":
        self.parts.append(np.ascontiguousarray(a, dtype=np.dtype(dtype).newbyteorder("<")).tobytes())
        return self

    def save(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"".join(self.parts))
